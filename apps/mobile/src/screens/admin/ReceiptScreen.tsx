import React, { useEffect, useState, useRef } from "react";
import {
  ActivityIndicator,
  Alert,
  Pressable,
  ScrollView,
  StyleSheet,
  Text,
  View,
  Image,
  Animated,
  Dimensions,
} from "react-native";
import { useNavigation } from "@react-navigation/native";
import { Ionicons } from "@expo/vector-icons";
import * as Print from "expo-print";
import * as Sharing from "expo-sharing";
import { api } from "../../api/client";

const { width } = Dimensions.get("window");

export default function ReceiptScreen({ route }: any) {
  const navigation = useNavigation<any>();
  const [pdfUri, setPdfUri] = useState<string | null>(null);
  const { paymentId } = route.params;
  const [receipt, setReceipt] = useState<any>(null);
  const [loading, setLoading] = useState(true);

  const fadeAnim = useRef(new Animated.Value(0)).current;
  const slideAnim = useRef(new Animated.Value(30)).current;
  const scaleAnim = useRef(new Animated.Value(0.95)).current;

  const animateIn = () => {
    Animated.parallel([
      Animated.timing(fadeAnim, {
        toValue: 1,
        duration: 500,
        useNativeDriver: true,
      }),
      Animated.timing(slideAnim, {
        toValue: 0,
        duration: 500,
        useNativeDriver: true,
      }),
      Animated.timing(scaleAnim, {
        toValue: 1,
        duration: 400,
        useNativeDriver: true,
      }),
    ]).start();
  };

  useEffect(() => {
    loadReceipt();
  }, []);

  const loadReceipt = async () => {
    try {
      setLoading(true);
      const res = await api.get(`/payments/${paymentId}/receipt`);
      setReceipt(res.data);
      animateIn();
    } catch (err) {
      Alert.alert("Error", "Unable to load receipt.");
    } finally {
      setLoading(false);
    }
  };

  const generateReceiptHtml = () => {
    const logoUrl = receipt.company?.logoUrl
      ? `${api.defaults.baseURL}/uploads/companies/${receipt.company.logoUrl}`
      : "";

    return `
<!DOCTYPE html>
<html>
<head>
<meta charset="utf-8" />
<style>
body { font-family: Arial, Helvetica, sans-serif; padding: 40px; color: #111827; }
.header { text-align: center; margin-bottom: 30px; }
.logo { width: 90px; height: 90px; object-fit: contain; margin-bottom: 10px; }
.company { font-size: 24px; font-weight: bold; }
.receipt { margin-top: 10px; color: #6d28d9; font-size: 20px; font-weight: bold; }
.number { color: #475569; margin-bottom: 25px; }
table { width: 100%; border-collapse: collapse; }
td { padding: 10px; border-bottom: 1px solid #e5e7eb; }
.label { font-weight: bold; width: 35%; }
.amount { font-size: 24px; color: #6d28d9; font-weight: bold; }
.footer { margin-top: 40px; text-align: center; color: #64748b; font-size: 12px; }
</style>
</head>
<body>
<div class="header">
${logoUrl ? `<img class="logo" src="${logoUrl}" />` : ""}
<div class="company">${receipt.company?.name}</div>
<div>${receipt.company?.address ?? ""}</div>
<div>${receipt.company?.phone ?? ""}</div>
<div>${receipt.company?.email ?? ""}</div>
<div class="receipt">PAYMENT RECEIPT</div>
<div class="number">${receipt.receiptNumber}</div>
</div>
<table>
<tr><td class="label">Equipment</td><td>${receipt.equipment?.name}</td></tr>
<tr><td class="label">Maintenance Plan</td><td>${receipt.plan?.name}</td></tr>
<tr><td class="label">Amount</td><td class="amount">₹${Number(receipt.amount).toLocaleString("en-IN")}</td></tr>
<tr><td class="label">Status</td><td>${receipt.status}</td></tr>
<tr><td class="label">Method</td><td>${receipt.method ?? "-"}</td></tr>
<tr><td class="label">Reference</td><td>${receipt.transactionReference ?? "-"}</td></tr>
<tr><td class="label">Payment Date</td><td>${new Date(receipt.paymentDate).toLocaleDateString()}</td></tr>
<tr><td class="label">Recorded By</td><td>${receipt.recordedBy?.name ?? "-"}</td></tr>
<tr><td class="label">Notes</td><td>${receipt.notes ?? "-"}</td></tr>
</table>
<div class="footer">Generated by Hydraulic Service Platform</div>
</body>
</html>
`;
  };

  const generatePdf = async () => {
    try {
      const html = generateReceiptHtml();
      const { uri } = await Print.printToFileAsync({ html });
      setPdfUri(uri);
      Alert.alert("Success", "Receipt PDF generated successfully.");
    } catch (err) {
      console.error(err);
      Alert.alert("Error", "Unable to generate receipt PDF.");
    }
  };

  const shareReceipt = async () => {
    try {
      let fileUri = pdfUri;
      if (!fileUri) {
        const html = generateReceiptHtml();
        const { uri } = await Print.printToFileAsync({ html });
        fileUri = uri;
        setPdfUri(uri);
      }
      const available = await Sharing.isAvailableAsync();
      if (!available) {
        Alert.alert("Unavailable", "Sharing is not available on this device.");
        return;
      }
      await Sharing.shareAsync(fileUri, {
        mimeType: "application/pdf",
        dialogTitle: "Share Payment Receipt",
      });
    } catch (err) {
      console.error(err);
      Alert.alert("Error", "Unable to share receipt.");
    }
  };

  if (loading) {
    return (
      <View style={styles.center}>
        <View style={styles.bgGradient}>
          <View style={[styles.bgOrb, styles.bgOrb1]} />
          <View style={[styles.bgOrb, styles.bgOrb2]} />
        </View>
        <ActivityIndicator size="large" color="#8b5cf6" />
        <Text style={styles.loadingText}>Loading receipt...</Text>
      </View>
    );
  }

  if (!receipt) {
    return (
      <View style={styles.center}>
        <View style={styles.bgGradient}>
          <View style={[styles.bgOrb, styles.bgOrb1]} />
        </View>
        <View style={styles.emptyCard}>
          <View style={styles.emptyGlow} />
          <View style={styles.emptyIconWrap}>
            <Ionicons name="receipt-outline" size={40} color="#8b5cf6" />
          </View>
          <Text style={styles.emptyTitle}>Receipt not found</Text>
          <Text style={styles.emptyText}>
            The payment receipt you're looking for doesn't exist or was removed.
          </Text>
          <Pressable
            style={styles.emptyBtn}
            onPress={() => navigation.goBack()}
          >
            <Ionicons name="arrow-back" size={16} color="#fff" />
            <Text style={styles.emptyBtnText}>Go Back</Text>
          </Pressable>
        </View>
      </View>
    );
  }

  const statusConfig =
    receipt.status === "success"
      ? {
          bg: "rgba(16, 185, 129, 0.15)",
          border: "rgba(16, 185, 129, 0.3)",
          text: "#34d399",
          bar: "#10b981",
        }
      : {
          bg: "rgba(239, 68, 68, 0.15)",
          border: "rgba(239, 68, 68, 0.3)",
          text: "#f87171",
          bar: "#ef4444",
        };

  const receiptItems = [
    { label: "Equipment", value: receipt.equipment?.name || "-" },
    { label: "Maintenance Plan", value: receipt.plan?.name || "-" },
    { label: "Method", value: receipt.method || "-" },
    { label: "Reference", value: receipt.transactionReference || "-" },
    {
      label: "Payment Date",
      value: new Date(receipt.paymentDate).toLocaleDateString("en-US", {
        month: "long",
        day: "numeric",
        year: "numeric",
      }),
    },
    { label: "Recorded By", value: receipt.recordedBy?.name || "-" },
  ];

  return (
    <View style={styles.screen}>
      {/* Background Orbs */}
      <View style={styles.bgGradient}>
        <View style={[styles.bgOrb, styles.bgOrb1]} />
        <View style={[styles.bgOrb, styles.bgOrb2]} />
        <View style={[styles.bgOrb, styles.bgOrb3]} />
      </View>

      <ScrollView
        style={styles.scroll}
        contentContainerStyle={styles.content}
        showsVerticalScrollIndicator={false}
      >
        {/* Header */}
        <Animated.View
          style={[
            styles.header,
            { opacity: fadeAnim, transform: [{ translateY: slideAnim }] },
          ]}
        >
          <Pressable onPress={() => navigation.goBack()} style={styles.backBtn}>
            <Ionicons name="arrow-back" size={22} color="#fff" />
          </Pressable>
          <View style={styles.headerCenter}>
            <Text style={styles.title}>Payment Receipt</Text>
            <Text style={styles.subtitle}>Transaction details</Text>
          </View>
          <View style={{ width: 44 }} />
        </Animated.View>

        {/* Receipt Card */}
        <Animated.View
          style={{ opacity: fadeAnim, transform: [{ scale: scaleAnim }] }}
        >
          <View
            style={[styles.receiptCard, { borderColor: statusConfig.border }]}
          >
            <View
              style={[styles.accentBar, { backgroundColor: statusConfig.bar }]}
            />

            {/* Watermark */}
            <View style={styles.watermark}>
              <Ionicons
                name="receipt"
                size={120}
                color="rgba(124, 58, 237, 0.03)"
              />
            </View>

            {/* Receipt Header */}
            <View style={styles.receiptHeader}>
              <Text style={styles.receiptTitle}>PAYMENT RECEIPT</Text>
              <Text style={styles.receiptNumber}>{receipt.receiptNumber}</Text>
              <View
                style={[
                  styles.statusBadge,
                  {
                    backgroundColor: statusConfig.bg,
                    borderColor: statusConfig.border,
                  },
                ]}
              >
                <Ionicons
                  name={
                    receipt.status === "success"
                      ? "checkmark-circle"
                      : "alert-circle"
                  }
                  size={14}
                  color={statusConfig.text}
                  style={{ marginRight: 6 }}
                />
                <Text style={[styles.statusText, { color: statusConfig.text }]}>
                  {receipt.status.toUpperCase()}
                </Text>
              </View>
            </View>

            <View style={styles.divider} />

            {/* Company Section */}
            <View style={styles.companySection}>
              {receipt.company?.logoUrl ? (
                <Image
                  source={{
                    uri: `${api.defaults.baseURL}/uploads/companies/${receipt.company.logoUrl}`,
                  }}
                  style={styles.companyLogo}
                  resizeMode="contain"
                />
              ) : (
                <View style={styles.logoPlaceholder}>
                  <Ionicons name="business" size={32} color="#8b5cf6" />
                </View>
              )}
              <View style={styles.companyDetails}>
                <Text style={styles.companyName}>{receipt.company?.name}</Text>
                {receipt.company?.address ? (
                  <Text style={styles.companyInfo}>
                    {receipt.company.address}
                  </Text>
                ) : null}
                {receipt.company?.phone ? (
                  <Text style={styles.companyInfo}>
                    {receipt.company.phone}
                  </Text>
                ) : null}
                {receipt.company?.email ? (
                  <Text style={styles.companyInfo}>
                    {receipt.company.email}
                  </Text>
                ) : null}
              </View>
            </View>

            <View style={styles.divider} />

            {/* Amount Section */}
            <View style={styles.amountSection}>
              <Text style={styles.amountLabel}>Total Amount</Text>
              <Text style={styles.amount}>
                ₹{Number(receipt.amount).toLocaleString("en-IN")}
              </Text>
            </View>

            <View style={styles.divider} />

            {/* Details Grid */}
            <View style={styles.detailsGrid}>
              {receiptItems.map((item, index) => (
                <View key={index} style={styles.detailItem}>
                  <Text style={styles.detailLabel}>{item.label}</Text>
                  <Text style={styles.detailValue} numberOfLines={2}>
                    {item.value}
                  </Text>
                </View>
              ))}
            </View>

            {/* Notes */}
            {receipt.notes ? (
              <>
                <View style={styles.divider} />
                <View style={styles.notesSection}>
                  <View style={styles.notesHeader}>
                    <Ionicons
                      name="document-text-outline"
                      size={16}
                      color="#a78bfa"
                    />
                    <Text style={styles.notesTitle}>Notes</Text>
                  </View>
                  <Text style={styles.notesText}>{receipt.notes}</Text>
                </View>
              </>
            ) : null}

            {/* Footer */}
            <View style={styles.receiptFooter}>
              <Ionicons
                name="shield-checkmark-outline"
                size={14}
                color="#4b5563"
              />
              <Text style={styles.receiptFooterText}>
                Generated by Hydraulic Service Platform
              </Text>
            </View>
          </View>
        </Animated.View>

        {/* Action Buttons */}
        <Animated.View
          style={{ opacity: fadeAnim, transform: [{ translateY: slideAnim }] }}
        >
          <Pressable
            style={({ pressed }) => [
              styles.primaryButton,
              pressed && { opacity: 0.85, transform: [{ scale: 0.98 }] },
            ]}
            onPress={generatePdf}
          >
            <View style={styles.btnIconWrap}>
              <Ionicons
                name="document-text-outline"
                size={20}
                color="#7c3aed"
              />
            </View>
            <View style={styles.btnTextWrap}>
              <Text style={styles.primaryButtonText}>Generate PDF</Text>
              <Text style={styles.btnSubtitle}>Save receipt as PDF file</Text>
            </View>
            <Ionicons name="download-outline" size={20} color="#a78bfa" />
          </Pressable>

          <View style={{ height: 10 }} />

          <Pressable
            style={({ pressed }) => [
              styles.secondaryButton,
              pressed && { opacity: 0.85, transform: [{ scale: 0.98 }] },
            ]}
            onPress={shareReceipt}
          >
            <View
              style={[
                styles.btnIconWrap,
                { backgroundColor: "rgba(59, 130, 246, 0.15)" },
              ]}
            >
              <Ionicons name="share-social-outline" size={20} color="#60a5fa" />
            </View>
            <View style={styles.btnTextWrap}>
              <Text style={styles.secondaryButtonText}>Share Receipt</Text>
              <Text style={styles.btnSubtitle}>
                Send via email or messaging
              </Text>
            </View>
            <Ionicons name="chevron-forward" size={20} color="#60a5fa" />
          </Pressable>
        </Animated.View>

        <View style={{ height: 30 }} />
      </ScrollView>
    </View>
  );
}

